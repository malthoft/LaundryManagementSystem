-- ---------------------------------------------------------------------------
-- 8. Pemeriksaan
-- ---------------------------------------------------------------------------
do $$
declare
  v_tabel int;
  v_rls   int;
  v_pol   int;
begin
  select count(*) into v_tabel
    from information_schema.tables
   where table_schema = 'public' and table_type = 'BASE TABLE';

  select count(*) into v_rls
    from pg_class c
    join pg_namespace n on n.oid = c.relnamespace
   where n.nspname = 'public' and c.relkind = 'r' and c.relrowsecurity;

  select count(*) into v_pol
    from pg_policies
   where schemaname = 'public';

  raise notice 'JoyOps: % tabel, % dengan RLS, % policy', v_tabel, v_rls, v_pol;

  if v_tabel <> 12 then
    raise warning 'Harapannya 12 tabel, terbaca %', v_tabel;
  end if;

  if v_rls <> v_tabel then
    raise warning 'Ada tabel tanpa RLS. Itu bug, bukan pilihan.';
  end if;
end $$;
