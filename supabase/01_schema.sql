-- 3.2 Apakah pengguna yang login seorang Admin
create or replace function public.adminkah()
returns boolean
language sql
stable
security definer
set search_path = public, pg_temp
as $$
  select coalesce((select role from public.profiles where id = auth.uid()) = 'Admin', false)
$$;

-- 3.3 Kirim notifikasi, fan-out ke penerima yang tepat
create or replace function public.notify(
  p_title         text,
  p_message       text,
  p_type          text default 'info',
  p_for_role      text default 'All',
  p_user_id       uuid default null,
  p_related_type  text default null,
  p_related_id    bigint default null
)
returns void
language plpgsql
security definer
set search_path = public, pg_temp
as $$
begin
  if p_user_id is not null then
    insert into public.notifications (user_id, title, message, type, related_type, related_id)
    values (p_user_id, p_title, p_message, p_type, p_related_type, p_related_id);
    return;
  end if;

  insert into public.notifications (user_id, title, message, type, related_type, related_id)
  select p.id, p_title, p_message, p_type, p_related_type, p_related_id
    from public.profiles p
   where p.is_active
     and (p_for_role is null or p_for_role = 'All' or p.role = p_for_role);
end;
$$;

-- 3.4 Lepaskan mesin yang tidak lagi dipakai order berjalan
create or replace function public.lepaskan_mesin_bebas()
returns void
language plpgsql
security definer
set search_path = public, pg_temp
as $$
begin
  update public.machines m
     set status = 'Tersedia',
         available_at = null
   where m.status = 'Digunakan'
     and not exists (
       select 1
         from public.orders o
        where o.status = 'Berjalan'
          and (o.washer_machine_id = m.id or o.dryer_machine_id = m.id)
     );
end;
$$;

-- 3.5 Tutup order yang sudah lewat end_time (pengganti "Order Otomatis Selesai")
create or replace function public.tutup_order_kedaluwarsa()
returns int
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_jumlah int;
begin
  with ditutup as (
    update public.orders
       set status = 'Selesai'
     where status = 'Berjalan'
       and end_time <= now()
    returning id, order_code
  )
  select count(*) into v_jumlah from ditutup;

  if v_jumlah > 0 then
    perform public.lepaskan_mesin_bebas();

    insert into public.notifications (user_id, title, message, type, related_type)
    select p.id, 'Order Otomatis Selesai',
           v_jumlah || ' order ditutup otomatis karena waktunya habis.', 'info', 'order'
      from public.profiles p
     where p.is_active;
  end if;

  return v_jumlah;
end;
$$;

-- 3.6 Ubah nama profil sendiri (tanpa izin mengubah peran)
create or replace function public.ubah_profil_saya(p_full_name text)
returns void
language plpgsql
security definer
set search_path = public, pg_temp
as $$
begin
  if p_full_name is null or length(btrim(p_full_name)) < 2 then
    raise exception 'Nama minimal 2 karakter' using errcode = '22023';
  end if;

  update public.profiles
     set full_name = btrim(p_full_name)
   where id = auth.uid();
end;
$$;

-- ---------------------------------------------------------------------------
-- 4. Fungsi inti: buat order, selesaikan order, batalkan order
--    Dijalankan sebagai security definer supaya:
--      a. status mesin bisa diubah walau karyawan tidak punya izin tulis mesin
--      b. seluruh langkah jadi satu transaksi, tidak ada data separuh jadi
--      c. dua order tidak bisa merebut mesin yang sama (row lock)
-- ---------------------------------------------------------------------------

-- 4.1 Buat order
create or replace function public.buat_order(
  p_washer_id       bigint,
  p_dryer_id        bigint,
  p_service_id      bigint,
  p_customer_name   text,
  p_qty             numeric,
  p_addon_ids       bigint[] default '{}',
  p_payment_method  text default 'Cash',
  p_notes           text default null
)
returns public.orders
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_saya      uuid := auth.uid();
  v_wm        public.machines;
  v_dm        public.machines;
  v_layanan   public.services;
  v_order     public.orders;
  v_qty       numeric(10,2);
  v_svc_total numeric(14,2);
  v_add_total numeric(14,2) := 0;
  v_durasi    int;
  v_kode      text;
begin
  if v_saya is null then
    raise exception 'Sesi tidak ditemukan' using errcode = '28000';
  end if;

  if not exists (select 1 from public.profiles where id = v_saya and is_active) then
    raise exception 'Akun tidak aktif' using errcode = '28000';
  end if;

  v_qty := round(coalesce(p_qty, 0), 2);
  if v_qty <= 0 then
    raise exception 'Qty harus lebih dari 0' using errcode = '22023';
  end if;

  if p_payment_method not in ('Cash','QRIS') then
    raise exception 'Metode pembayaran tidak dikenal' using errcode = '22023';
  end if;

  -- Kunci kedua mesin. Kunci baris mencegah dua order merebut mesin yang sama.
  select * into v_wm from public.machines where id = p_washer_id for update;
  if not found then
    raise exception 'Mesin cuci tidak ditemukan' using errcode = '22023';
  end if;

  select * into v_dm from public.machines where id = p_dryer_id for update;
  if not found then
    raise exception 'Mesin pengering tidak ditemukan' using errcode = '22023';
  end if;

  if v_wm.id = v_dm.id then
    raise exception 'Mesin cuci dan pengering harus berbeda' using errcode = '22023';
  end if;

  if v_wm.machine_code not like 'WM-%' then
    raise exception 'Mesin % bukan mesin cuci', v_wm.machine_code using errcode = '22023';
  end if;

  if v_dm.machine_code not like 'DM-%' then
    raise exception 'Mesin % bukan mesin pengering', v_dm.machine_code using errcode = '22023';
  end if;

  if v_wm.status <> 'Tersedia' then
    raise exception 'Mesin % sedang tidak tersedia', v_wm.machine_code using errcode = '22023';
  end if;

  if v_dm.status <> 'Tersedia' then
    raise exception 'Mesin % sedang tidak tersedia', v_dm.machine_code using errcode = '22023';
  end if;

  select * into v_layanan from public.services where id = p_service_id and is_active;
  if not found then
    raise exception 'Layanan tidak ditemukan atau tidak aktif' using errcode = '22023';
  end if;

  v_durasi := greatest(coalesce(v_layanan.duration_minutes, 90), 1);  -- BR-05
  v_svc_total := round(v_layanan.price * v_qty, 2);

  -- Kode order: ORD-YYYYMMDD-NNNN, urut per hari
  v_kode := 'ORD-' || to_char(now() at time zone 'Asia/Jakarta', 'YYYYMMDD') || '-' ||
            lpad((
              select coalesce(count(*), 0) + 1
                from public.orders o
               where (o.created_at at time zone 'Asia/Jakarta')::date
                     = (now() at time zone 'Asia/Jakarta')::date
            )::text, 4, '0');

  insert into public.orders (
    order_code, washer_machine_id, dryer_machine_id, service_id,
    customer_name, qty, service_price, addon_total, grand_total,
    duration_minutes, start_time, end_time, status, payment_method, notes, created_by
  ) values (
    v_kode, v_wm.id, v_dm.id, v_layanan.id,
    coalesce(nullif(btrim(p_customer_name), ''), 'Walk-in'), v_qty, v_svc_total, 0, v_svc_total,
    v_durasi, now(), now() + make_interval(mins => v_durasi),
    'Berjalan', p_payment_method, nullif(btrim(coalesce(p_notes, '')), ''), v_saya
  )
  returning * into v_order;

  -- Add-on. Harga dan nama disalin ke baris order (BR-08).
  if p_addon_ids is not null and array_length(p_addon_ids, 1) > 0 then
    insert into public.order_addons (order_id, addon_id, addon_name, qty, price, subtotal)
    select v_order.id, a.id, a.addon_name, 1, a.price, round(a.price * 1, 2)
      from public.addons a
     where a.id = any(p_addon_ids)
       and a.is_active;

    select coalesce(sum(oa.subtotal), 0) into v_add_total
      from public.order_addons oa
     where oa.order_id = v_order.id;
  end if;

  -- Total akhir dihitung di server (BR-06)
  update public.orders
     set addon_total = v_add_total,
         grand_total = round(v_svc_total + v_add_total, 2)
   where id = v_order.id
  returning * into v_order;

  -- Mesin dipakai (BR-07)
  update public.machines
     set status = 'Digunakan',
         last_used = now(),
         available_at = v_order.end_time
   where id in (v_wm.id, v_dm.id);

  -- Pemasukan otomatis
  insert into public.transactions (transaction_date, transaction_type, amount, payment_method, description, order_id, created_by)
  values (
    (now() at time zone 'Asia/Jakarta')::date,
    'Pemasukan',
    v_order.grand_total,
    v_order.payment_method,
    'Order ' || v_order.order_code || ' - ' || v_wm.machine_code || ' & ' || v_dm.machine_code ||
      ' - ' || v_layanan.service_name || ' (' || trim(to_char(v_qty, 'FM999999990.##')) || ' ' || v_layanan.unit || ')',
    v_order.id,
    v_saya
  )
  on conflict (order_id) do nothing;

  perform public.notify(
    'Order Baru',
    'Order ' || v_order.order_code || ' untuk ' || v_wm.machine_code || ' & ' || v_dm.machine_code ||
      ' - ' || v_order.customer_name || '. Total: Rp ' ||
      to_char(v_order.grand_total, 'FM999,999,999'),
    'success', 'All', null, 'order', v_order.id
  );

  return v_order;
end;
$$;

-- 4.2 Selesaikan order
create or replace function public.selesaikan_order(p_order_id bigint)
returns void
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_order public.orders;
begin
  if auth.uid() is null then
    raise exception 'Sesi tidak ditemukan' using errcode = '28000';
  end if;

  select * into v_order from public.orders where id = p_order_id for update;
  if not found then
    raise exception 'Order tidak ditemukan' using errcode = '22023';
  end if;

  if v_order.status <> 'Berjalan' then
    raise exception 'Order % sudah tidak berjalan', v_order.order_code using errcode = '22023';
  end if;

  update public.orders set status = 'Selesai' where id = p_order_id;
  perform public.lepaskan_mesin_bebas();

  perform public.notify(
    'Order Selesai',
    'Order ' || v_order.order_code || ' telah selesai. Mesin kembali tersedia.',
    'info', 'All', null, 'order', p_order_id
  );
end;
$$;

-- 4.3 Batalkan order (Admin saja)
create or replace function public.batalkan_order(p_order_id bigint, p_alasan text default null)
returns void
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_order public.orders;
begin
  if not public.adminkah() then
    raise exception 'Hanya Admin yang boleh membatalkan order' using errcode = '42501';
  end if;

  select * into v_order from public.orders where id = p_order_id for update;
  if not found then
    raise exception 'Order tidak ditemukan' using errcode = '22023';
  end if;

  if v_order.status = 'Dibatalkan' then
    return;
  end if;

  update public.orders
     set status = 'Dibatalkan',
         notes = coalesce(nullif(btrim(p_alasan), ''), notes)
   where id = p_order_id;

  -- Pemasukan order batal tidak boleh ikut terhitung
  delete from public.transactions where order_id = p_order_id;

  perform public.lepaskan_mesin_bebas();

  perform public.notify(
    'Order Dibatalkan',
    'Order ' || v_order.order_code || ' dibatalkan.' ||
      case when p_alasan is null or btrim(p_alasan) = '' then '' else ' Alasan: ' || p_alasan end,
    'warning', 'All', null, 'order', p_order_id
  );
end;
$$;

-- 4.4 Setujui tukar shift (Admin). Menukar pemilik kedua shift.
create or replace function public.setujui_tukar_shift(p_permintaan_id bigint, p_setuju boolean)
returns void
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_req    public.shift_swap_requests;
  v_shift  public.shifts;
  v_target public.shifts;
  v_status text;
begin
  if not public.adminkah() then
    raise exception 'Hanya Admin yang boleh menyetujui tukar shift' using errcode = '42501';
  end if;

  select * into v_req from public.shift_swap_requests where id = p_permintaan_id for update;
  if not found then
    raise exception 'Pengajuan tidak ditemukan' using errcode = '22023';
  end if;

  if v_req.status <> 'Accepted by Employee' then
    raise exception 'Pengajuan belum diterima rekan kerja' using errcode = '22023';
  end if;

  if p_setuju then
    select * into v_shift  from public.shifts where id = v_req.shift_id        for update;
    select * into v_target from public.shifts where id = v_req.target_shift_id for update;

    if v_shift.id is null or v_target.id is null then
      raise exception 'Shift sudah tidak ada' using errcode = '22023';
    end if;

    update public.shifts set profile_id = v_target.profile_id where id = v_shift.id;
    update public.shifts set profile_id = v_shift.profile_id  where id = v_target.id;

    v_status := 'Approved';

    perform public.notify('Tukar Shift Disetujui',
      'Tukar shift ' || v_shift.work_date || ' disetujui Admin. Jadwal sudah diperbarui.',
      'success', 'All', null, 'shift_swap', p_permintaan_id);
  else
    v_status := 'Rejected by Admin';

    perform public.notify('Tukar Shift Ditolak',
      'Tukar shift ditolak Admin. Jadwal tidak berubah.',
      'warning', 'All', null, 'shift_swap', p_permintaan_id);
  end if;

  update public.shift_swap_requests
     set status = v_status,
         decided_by = auth.uid(),
         decided_at = now()
   where id = p_permintaan_id;
end;
$$;

-- 4.5 Clock in / clock out
create or replace function public.absen_masuk(p_shift_id bigint default null)
returns public.attendance
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_saya   uuid := auth.uid();
  v_hasil  public.attendance;
  v_tanggal date := (now() at time zone 'Asia/Jakarta')::date;
begin
  if v_saya is null then
    raise exception 'Sesi tidak ditemukan' using errcode = '28000';
  end if;

  insert into public.attendance (profile_id, shift_id, work_date, clock_in, status)
  values (v_saya, p_shift_id, v_tanggal, now(), 'Pending')
  on conflict (profile_id, work_date) do update
     set clock_in = coalesce(public.attendance.clock_in, now()),
         shift_id = coalesce(public.attendance.shift_id, excluded.shift_id)
  returning * into v_hasil;

  if p_shift_id is not null then
    update public.shifts set status = 'Clocked In' where id = p_shift_id;
  end if;

  perform public.notify('Absen Masuk',
    'Seorang karyawan melakukan clock in.', 'info', 'Admin', null, 'attendance', v_hasil.id);

  return v_hasil;
end;
$$;

create or replace function public.absen_keluar()
returns public.attendance
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_saya   uuid := auth.uid();
  v_hasil  public.attendance;
  v_tanggal date := (now() at time zone 'Asia/Jakarta')::date;
begin
  if v_saya is null then
    raise exception 'Sesi tidak ditemukan' using errcode = '28000';
  end if;

  update public.attendance
     set clock_out = now()
   where profile_id = v_saya and work_date = v_tanggal
  returning * into v_hasil;

  if v_hasil.id is null then
    raise exception 'Belum ada absen masuk hari ini' using errcode = '22023';
  end if;

  update public.shifts
     set status = 'Completed'
   where id = v_hasil.shift_id;

  return v_hasil;
end;
$$;

-- ---------------------------------------------------------------------------
-- 5. Trigger: profil otomatis saat akun auth dibuat
-- ---------------------------------------------------------------------------
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_username text;
  v_nama     text;
  v_peran    text;
begin
  v_username := lower(coalesce(
    nullif(new.raw_user_meta_data->>'username', ''),
    split_part(new.email, '@', 1)
  ));
  v_nama  := coalesce(nullif(new.raw_user_meta_data->>'full_name', ''), initcap(v_username));
  v_peran := coalesce(nullif(new.raw_user_meta_data->>'role', ''), 'Karyawan');

  if v_peran not in ('Admin','Karyawan') then
    v_peran := 'Karyawan';
  end if;

  insert into public.profiles (id, username, full_name, role, legacy_id)
  values (
    new.id,
    v_username,
    v_nama,
    v_peran,
    nullif(new.raw_user_meta_data->>'legacy_id', '')::int
  )
  on conflict (id) do nothing;

  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
after insert on auth.users
for each row execute function public.handle_new_user();

