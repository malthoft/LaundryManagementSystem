-- 1.1 profiles : pengguna aplikasi, 1:1 dengan auth.users
create table if not exists public.profiles (
  id          uuid primary key references auth.users(id) on delete cascade,
  username    text not null unique check (username = lower(username) and username ~ '^[a-z0-9._-]{3,30}$'),
  full_name   text not null check (length(btrim(full_name)) between 2 and 100),
  role        text not null default 'Karyawan' check (role in ('Admin','Karyawan')),
  legacy_id   int,
  is_active   boolean not null default true,
  created_at  timestamptz not null default now()
);

comment on table  public.profiles is 'Pengguna JoyOps. Password tidak di sini, ditangani Supabase Auth.';
comment on column public.profiles.username is 'Dipakai untuk login, dipetakan ke <username>@<AUTH_EMAIL_DOMAIN>.';
comment on column public.profiles.legacy_id is 'ID pada tabel users versi PHP, untuk penelusuran migrasi.';

-- 1.2 machines : mesin cuci dan pengering
create table if not exists public.machines (
  id            bigint generated by default as identity primary key,
  machine_code  text not null unique check (machine_code ~ '^[A-Z]{2}-[0-9]{2,3}$'),
  machine_type  text not null,
  status        text not null default 'Tersedia' check (status in ('Tersedia','Digunakan','Maintenance')),
  last_used     timestamptz,
  available_at  timestamptz,
  created_at    timestamptz not null default now()
);

comment on column public.machines.machine_code is 'Awalan WM- untuk mesin cuci, DM- untuk mesin pengering.';
comment on column public.machines.available_at is 'Perkiraan mesin bebas, diisi dari end_time order yang sedang berjalan.';

-- 1.3 services : layanan laundry
create table if not exists public.services (
  id                bigint generated by default as identity primary key,
  service_name      text not null check (length(btrim(service_name)) between 2 and 100),
  price             numeric(12,2) not null check (price >= 0),
  unit              text not null default 'kg' check (unit in ('kg','pcs')),
  duration_minutes  int  not null default 90 check (duration_minutes >= 1),
  icon              text not null default 'local_laundry_service',
  is_active         boolean not null default true,
  created_at        timestamptz not null default now()
);

comment on column public.services.unit is 'Satuan qty pada order: kg untuk kiloan, pcs untuk satuan.';
comment on column public.services.duration_minutes is 'Durasi standar pengerjaan. Disalin ke order saat order dibuat.';

-- 1.4 addons : layanan tambahan
create table if not exists public.addons (
  id          bigint generated by default as identity primary key,
  addon_name  text not null check (length(btrim(addon_name)) between 2 and 100),
  price       numeric(12,2) not null default 0 check (price >= 0),
  icon        text not null default 'add_circle',
  is_active   boolean not null default true,
  created_at  timestamptz not null default now()
);

-- 1.5 orders : order pelanggan
create table if not exists public.orders (
  id                 bigint generated by default as identity primary key,
  order_code         text not null unique,
  washer_machine_id  bigint not null references public.machines(id) on delete restrict,
  dryer_machine_id   bigint not null references public.machines(id) on delete restrict,
  service_id         bigint not null references public.services(id) on delete restrict,
  customer_name      text not null default 'Walk-in' check (length(btrim(customer_name)) between 1 and 100),
  qty                numeric(10,2) not null default 1 check (qty > 0),
  service_price      numeric(14,2) not null default 0 check (service_price >= 0),
  addon_total        numeric(14,2) not null default 0 check (addon_total >= 0),
  grand_total        numeric(14,2) not null default 0 check (grand_total >= 0),
  duration_minutes   int  not null default 90 check (duration_minutes >= 1),
  start_time         timestamptz not null default now(),
  end_time           timestamptz not null,
  status             text not null default 'Berjalan' check (status in ('Berjalan','Selesai','Dibatalkan')),
  payment_method     text not null default 'Cash' check (payment_method in ('Cash','QRIS')),
  notes              text,
  created_by         uuid not null references public.profiles(id) on delete restrict,
  created_at         timestamptz not null default now(),
  constraint order_mesin_harus_beda check (washer_machine_id <> dryer_machine_id),
  constraint order_waktu_wajar      check (end_time > start_time)
);

comment on column public.orders.washer_machine_id is 'Mesin cuci. Wajib, BR-01.';
comment on column public.orders.dryer_machine_id  is 'Mesin pengering. Wajib, BR-01.';

-- 1.6 order_addons : add-on per order (harga disalin, BR-08)
create table if not exists public.order_addons (
  id          bigint generated by default as identity primary key,
  order_id    bigint not null references public.orders(id) on delete cascade,
  addon_id    bigint not null references public.addons(id) on delete restrict,
  addon_name  text not null,
  qty         numeric(10,2) not null default 1 check (qty > 0),
  price       numeric(12,2) not null default 0 check (price >= 0),
  subtotal    numeric(14,2) not null default 0 check (subtotal >= 0),
  unique (order_id, addon_id)
);

-- 1.7 transactions : buku kas
