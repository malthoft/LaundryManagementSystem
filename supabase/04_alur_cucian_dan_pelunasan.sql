-- 6.1 Tandai cucian siap diambil dan titipkan ke rak
create or replace function public.tandai_siap_ambil(
  p_order_id bigint,
  p_rack_id  bigint default null
)
returns void
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_order public.orders;
begin
  select * into v_order from public.orders where id = p_order_id for update;
  if not found then
    raise exception 'Order % tidak ditemukan', p_order_id;
  end if;

  if v_order.status in ('Sudah Diambil','Dibatalkan') then
    raise exception 'Order % sudah diambil atau dibatalkan', v_order.order_code;
  end if;

  if p_rack_id is not null and not exists (
    select 1 from public.racks where id = p_rack_id and is_active
  ) then
    raise exception 'Rak % tidak ada atau tidak aktif', p_rack_id;
  end if;

  update public.orders
     set status     = 'Siap Ambil',
         rack_id    = coalesce(p_rack_id, rack_id),
         stored_at  = coalesce(stored_at, now()),
         pickup_due = coalesce(pickup_due, now() + interval '3 days')
   where id = p_order_id;

  perform public.notify(
    'Cucian Siap Ambil',
    'Order ' || v_order.order_code || ' sudah siap diambil.',
    'success', 'All', null, 'order', p_order_id
  );
end;
$$;

comment on function public.tandai_siap_ambil(bigint, bigint) is
  'Set status Siap Ambil, titipkan ke rak, dan tetapkan batas pengambilan 3 hari.';

-- 6.2 Pelunasan nota
-- Boleh dipanggil sebagian untuk DP. Pemasukan dicatat sebesar pembayaran itu
-- saja, jadi buku kas selalu sama dengan uang yang benar-benar diterima.
-- Mengembalikan sisa tagihan setelah pembayaran ini; 0 berarti lunas.
create or replace function public.lunasi_order(
  p_order_id bigint,
  p_jumlah   numeric,
  p_metode   text default 'Cash'
)
returns numeric
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_order public.orders;
  v_sisa  numeric(14,2);
  v_bayar numeric(14,2);
begin
  if p_jumlah is null or p_jumlah <= 0 then
    raise exception 'Jumlah bayar harus lebih dari nol';
  end if;

  if p_metode is null or p_metode not in ('Cash','QRIS','Transfer') then
    raise exception 'Metode bayar % tidak dikenal', coalesce(p_metode, 'kosong');
  end if;

  select * into v_order from public.orders where id = p_order_id for update;
  if not found then
    raise exception 'Order % tidak ditemukan', p_order_id;
  end if;

  if v_order.status = 'Dibatalkan' then
    raise exception 'Order % sudah dibatalkan', v_order.order_code;
  end if;

  v_sisa := v_order.grand_total - v_order.paid_amount;
  if v_sisa <= 0 then
    raise exception 'Order % sudah lunas', v_order.order_code;
  end if;

  v_bayar := least(p_jumlah, v_sisa);

  insert into public.transactions (
    transaction_type, amount, payment_method, description, order_id, created_by
  ) values (
    'Pemasukan', v_bayar, p_metode, 'Pelunasan ' || v_order.order_code, p_order_id, auth.uid()
  );

  update public.orders
     set paid_amount    = paid_amount + v_bayar,
         payment_status = case
                            when paid_amount + v_bayar >= grand_total then 'Lunas'
                            else 'DP'
                          end,
         paid_at        = now()
   where id = p_order_id;

  return v_sisa - v_bayar;
end;
$$;

comment on function public.lunasi_order(bigint, numeric, text) is
  'Catat pembayaran nota, boleh sebagian. Mengembalikan sisa tagihan.';

-- 6.3 Tandai sudah diambil dan kosongkan rak
create or replace function public.cucian_diambil(p_order_id bigint, p_metode text default 'Cash')
returns void
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_order public.orders;
begin
  select * into v_order from public.orders where id = p_order_id for update;
  if not found then
    raise exception 'Order % tidak ditemukan', p_order_id;
  end if;

  if v_order.status = 'Dibatalkan' then
    raise exception 'Order % sudah dibatalkan', v_order.order_code;
  end if;

  if v_order.paid_amount < v_order.grand_total then
    raise exception 'Order % belum lunas, sisa %', v_order.order_code,
      to_char(v_order.grand_total - v_order.paid_amount, 'FM999999990.00');
  end if;

  update public.orders
     set status   = 'Sudah Diambil',
         rack_id  = null,
         paid_at  = coalesce(paid_at, now())
   where id = p_order_id;
end;
$$;

comment on function public.cucian_diambil(bigint, text) is
  'Tutup order setelah lunas dan pelanggan mengambil cucian. Mengosongkan rak.';

