-- ---------------------------------------------------------------------------
-- 1. Status order
-- 'Berjalan' dan 'Selesai' tetap dipertahankan supaya UI versi sekarang masih
-- jalan sebelum ikut diperbarui. Rantai yang dituju:
--     Antre -> Dicuci -> Dikeringkan -> Disetrika -> Siap Ambil -> Sudah Diambil
-- dan Dibatalkan dari titik mana pun.
-- ---------------------------------------------------------------------------
alter table public.orders drop constraint if exists orders_status_check;

alter table public.orders
  add constraint orders_status_check check (
    status in (
      'Berjalan','Antre','Dicuci','Dikeringkan','Disetrika',
      'Siap Ambil','Sudah Diambil','Selesai','Dibatalkan'
    )
  );

-- ---------------------------------------------------------------------------
-- 2. racks : rak simpan
-- Tanpa kode rak, cucian yang sudah selesai tidak bisa ditemukan kembali saat
-- pelanggan datang. Kolom note dipakai untuk lokasi fisik, misalnya "dekat kasir".
-- ---------------------------------------------------------------------------
create table if not exists public.racks (
  id          bigint generated by default as identity primary key,
  rack_code   text not null unique check (rack_code ~ '^R-[0-9]{2,3}$'),
  capacity    int  not null default 10 check (capacity > 0),
  note        text,
  is_active   boolean not null default true,
  created_at  timestamptz not null default now()
);

comment on column public.racks.rack_code is 'Kode rak, pola R-01. Ditempel di rak fisiknya.';
comment on column public.racks.capacity is 'Jumlah maksimal kantong per rak. Dipakai untuk memperingatkan rak penuh.';

alter table public.racks enable row level security;

drop policy if exists racks_baca on public.racks;
create policy racks_baca on public.racks
  for select to authenticated
  using (true);

drop policy if exists racks_tulis on public.racks;
create policy racks_tulis on public.racks
  for all to authenticated
  using (public.adminkah())
  with check (public.adminkah());

-- ---------------------------------------------------------------------------
-- 3. orders : kolom yang kurang
-- ---------------------------------------------------------------------------
alter table public.orders
  add column if not exists rack_id          bigint references public.racks(id) on delete set null,
  add column if not exists stored_at        timestamptz,
  add column if not exists pickup_due       timestamptz,
  add column if not exists promised_done_at timestamptz,
  add column if not exists qty_final        numeric(10,2) check (qty_final is null or qty_final > 0),
  add column if not exists is_express       boolean not null default false,
  add column if not exists express_fee      numeric(14,2) not null default 0 check (express_fee >= 0),
  add column if not exists payment_status   text not null default 'Belum Lunas'
                                            check (payment_status in ('Belum Lunas','DP','Lunas')),
  add column if not exists paid_amount      numeric(14,2) not null default 0 check (paid_amount >= 0),
  add column if not exists paid_at          timestamptz,
  add column if not exists cancelled_at     timestamptz,
  add column if not exists cancelled_by     uuid references public.profiles(id) on delete set null,
  add column if not exists cancel_reason    text;

comment on column public.orders.qty_final is 'Hasil timbang akhir. Diisi kalau berbeda dari qty saat penerimaan.';
comment on column public.orders.promised_done_at is 'Janji selesai ke pelanggan. Beda dari end_time yang hanya menandai mesin bebas.';
comment on column public.orders.pickup_due is 'Batas waktu pengambilan. Setelah ini cucian boleh dikenai biaya simpan.';
comment on column public.orders.cancel_reason is 'Alasan pembatalan. Semula ditulis ke notes sehingga catatan asli tertimpa.';

-- ---------------------------------------------------------------------------
-- 4. machines : kapasitas
-- Tanpa kapasitas, sistem tidak bisa menyarankan mesin untuk beban 7 kg atau
-- memperingatkan mesin kelebihan muat.
-- ---------------------------------------------------------------------------
alter table public.machines
  add column if not exists capacity_kg numeric(5,2) check (capacity_kg is null or capacity_kg > 0);

comment on column public.machines.capacity_kg is 'Kapasitas cuci atau kering dalam kilogram.';

-- ---------------------------------------------------------------------------
-- 5. transactions : pelunasan bertahap
-- order_id semula UNIQUE, sehingga DP lalu pelunasan tidak mungkin dicatat
-- sebagai dua baris. Batas uniknya dilepas, diganti indeks biasa.
-- ---------------------------------------------------------------------------
alter table public.transactions drop constraint if exists transactions_order_id_key;

create index if not exists idx_transactions_order on public.transactions (order_id);

